      <p>
        Angebote des Auftragnehmers sind freibleibend und unverbindlich, sofern sie nicht
        ausdrücklich als verbindlich bezeichnet sind. Ein Vertrag kommt erst durch schriftliche
        Auftragsbestätigung oder durch Beginn der Leistungserbringung zustande.
      </p>
      <p>
        Mündliche Nebenabreden bedürfen der schriftlichen Bestätigung, um wirksam zu sein.
      </p>

      <h2>§ 3 Leistungsumfang</h2>
      <p>
        Der Umfang der zu erbringenden Leistungen ergibt sich aus dem jeweiligen Angebot bzw.
        der Auftragsbestätigung. Änderungen oder Erweiterungen des Leistungsumfangs bedürfen
        einer schriftlichen Vereinbarung und können zu einer Anpassung von Vergütung und
        Zeitplanung führen.
      </p>
      <p>
        Der Auftragnehmer ist berechtigt, zur Erbringung der Leistungen qualifizierte Dritte
        (Subunternehmer) einzusetzen, bleibt jedoch gegenüber dem Auftraggeber für die
        ordnungsgemäße Erfüllung verantwortlich.
      </p>

      <h2>§ 4 Mitwirkungspflichten des Auftraggebers</h2>
      <p>
        Der Auftraggeber verpflichtet sich, alle für die Leistungserbringung erforderlichen
        Informationen, Materialien und Zugänge rechtzeitig zur Verfügung zu stellen. Verzögerungen
        aufgrund fehlender oder unvollständiger Mitwirkung des Auftraggebers gehen nicht zu
        Lasten des Auftragnehmers und können zu einer entsprechenden Verschiebung vereinbarter
        Termine führen.
      </p>

      <h2>§ 5 Vergütung und Zahlungsbedingungen</h2>
      <p>
        Die Vergütung richtet sich nach dem jeweiligen Angebot. Alle Preise verstehen sich
        netto zuzüglich der gesetzlichen Umsatzsteuer, soweit diese anfällt. Als Kleinunternehmer
        gemäß § 19 UStG wird keine Umsatzsteuer erhoben.
      </p>
      <p>
        Rechnungen sind ohne Abzug innerhalb von 14 Tagen nach Rechnungsdatum fällig. Bei
        Zahlungsverzug ist der Auftragnehmer berechtigt, Verzugszinsen in Höhe von 9 Prozentpunkten
        über dem Basiszinssatz zu berechnen.
      </p>
      <p>
        Bei Projekten mit einem Gesamtvolumen ab 1.000 € kann eine Anzahlung von bis zu 50 %
        des Auftragswertes vor Beginn der Arbeiten vereinbart werden.
      </p>

      <h2>§ 6 Nutzungsrechte und geistiges Eigentum</h2>
      <p>
        Mit vollständiger Bezahlung der vereinbarten Vergütung erhält der Auftraggeber das
        einfache, zeitlich unbeschränkte Nutzungsrecht an den für ihn erstellten Arbeitsergebnissen
        für die vertraglich vereinbarte Nutzung.
      </p>
      <p>
        Werkzeuge, Frameworks, Bibliotheken und Methoden, die der Auftragnehmer im Rahmen der
        Leistungserbringung einsetzt und die nicht speziell für den Auftraggeber entwickelt wurden,
        verbleiben im Eigentum des Auftragnehmers. Der Auftragnehmer behält das Recht, diese auch
        für andere Auftraggeber einzusetzen.
      </p>

      <h2>§ 7 Gewährleistung und Mängelhaftung</h2>
      <p>
        Der Auftragnehmer leistet Gewähr für die vertragsgemäße Beschaffenheit der Arbeitsergebnisse.
        Mängel sind unverzüglich, spätestens innerhalb von 14 Tagen nach Entdeckung, schriftlich
        anzuzeigen. Der Auftragnehmer hat das Recht zur Nacherfüllung. Schlägt die Nacherfüllung
        zweimal fehl, kann der Auftraggeber Minderung oder Rücktritt verlangen.
      </p>
      <p>
        Die Gewährleistungsfrist beträgt ein Jahr ab Abnahme der Leistung.
      </p>

      <h2>§ 8 Haftungsbeschränkung</h2>
      <p>
        Der Auftragnehmer haftet unbeschränkt für Schäden aus der Verletzung des Lebens, des
        Körpers oder der Gesundheit sowie für Schäden, die auf Vorsatz oder grober Fahrlässigkeit
        beruhen.
      </p>
      <p>
        Für leichte Fahrlässigkeit haftet der Auftragnehmer nur bei Verletzung wesentlicher
        Vertragspflichten (Kardinalpflichten), und zwar begrenzt auf den vorhersehbaren,
        vertragstypischen Schaden, maximal jedoch auf den Auftragswert des betreffenden Projekts.
        Eine weitergehende Haftung ist ausgeschlossen.
      </p>

      <h2>§ 9 Vertraulichkeit</h2>
      <p>
        Beide Parteien verpflichten sich, alle im Rahmen des Vertragsverhältnisses bekannt
        gewordenen vertraulichen Informationen der jeweils anderen Partei vertraulich zu
        behandeln und nicht an Dritte weiterzugeben. Diese Verpflichtung gilt auch nach
        Beendigung des Vertragsverhältnisses.
      </p>

      <h2>§ 10 Kündigung</h2>
      <p>
        Laufende Projekte können von beiden Seiten mit einer Frist von 14 Tagen schriftlich
        gekündigt werden. Bereits erbrachte Leistungen sind in jedem Fall zu vergüten. Für
        die Zeit zwischen Kündigung und vereinbartem Projektende kann der Auftragnehmer
        entgangenen Gewinn geltend machen, sofern die Kündigung ohne wichtigen Grund erfolgt.
      </p>

